"""Regenerate preserving doctrine decisions and the doctrine-screen selector."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def tokenize(text):
    return re.findall(r'"(?:\\.|[^"\\])*"|[^\s={}#"]+|[={} ]',
                      re.sub(r'#[^\n]*', '', text.replace('\ufeff', '')))


def parse(text):
    tokens = [t for t in tokenize(text) if t != ' ']
    position = 0

    def block(nested=False):
        nonlocal position
        result = []
        while position < len(tokens):
            key = tokens[position]
            position += 1
            if key == '}':
                if not nested:
                    raise ValueError('Unexpected closing brace')
                return result
            if key == '{':
                result.append((None, block(True)))
                continue
            if position < len(tokens) and tokens[position] in ('=', '>', '<'):
                operator = tokens[position]
                position += 1
                value = tokens[position]
                position += 1
                if value == '{':
                    value = block(True)
                result.append((key if operator == '=' else key + ' ' + operator, value))
            else:
                result.append((None, key))
        if nested:
            raise ValueError('Unclosed block')
        return result

    return block()


def read(path):
    return parse(path.read_text(encoding='utf-8-sig'))


def get(block, key):
    return next(v for k, v in block if k == key)


def track_effects(track, folder):
    # HOI4 does not expand the $PARAMETER$ scripted-effect syntax used by
    # the old fix. Generate concrete effects and call them with '= yes'.
    template = (ROOT / 'tools/doctrine_switch_effects.template.txt').read_text(encoding='utf-8')
    digits = []
    for digit in range(1, 6):
        digits.append(f'''    set_variable = {{ tfr_doctrine_low = 0 }}
    set_variable = {{ tfr_doctrine_high = 10 }}
    set_variable = {{ tfr_doctrine_gap = 10 }}
    while_loop_effect = {{
        limit = {{ check_variable = {{ tfr_doctrine_gap > 1 }} }}
        set_variable = {{ tfr_doctrine_mid = tfr_doctrine_low }}
        add_to_variable = {{ tfr_doctrine_mid = tfr_doctrine_high }}
        divide_variable = {{ tfr_doctrine_mid = 2 }}
        round_variable = tfr_doctrine_mid
        set_variable = {{ tfr_doctrine_d{digit} = tfr_doctrine_mid }}
        tfr_probe_track_mastery = {{ TRACK = $TRACK$ }}
        if = {{
            limit = {{ check_variable = {{ tfr_doctrine_probe_pass = 1 }} }}
            set_variable = {{ tfr_doctrine_low = tfr_doctrine_mid }}
        }}
        else = {{ set_variable = {{ tfr_doctrine_high = tfr_doctrine_mid }} }}
        set_variable = {{ tfr_doctrine_gap = tfr_doctrine_high }}
        subtract_from_variable = {{ tfr_doctrine_gap = tfr_doctrine_low }}
    }}
    set_variable = {{ tfr_doctrine_d{digit} = tfr_doctrine_low }}
    set_variable = {{ tfr_saved_mastery_$TRACK$_d{digit} = tfr_doctrine_low }}''')
    template = template.replace('$DIGIT_SEARCH$', '\n'.join(digits))
    return (template.replace('$TRACK$', track).replace('$FOLDER$', folder)
            .replace('tfr_probe_track_mastery', 'tfr_probe_' + track + '_mastery')
            .replace('tfr_save_track_mastery', 'tfr_save_' + track + '_mastery')
            .replace('tfr_restore_track_mastery', 'tfr_restore_' + track + '_mastery')
            .replace(' = { TRACK = ' + track + ' }', ' = yes'))


def main():
    definitions = {}
    for path in sorted((ROOT / 'common/doctrines/subdoctrines').rglob('*.txt')):
        for name, fields in read(path):
            track = get(fields, 'track')
            if isinstance(track, str):
                definitions.setdefault(track, []).append(name)

    counter_names = {
        'infantry': 'infantry', 'combat_support': 'support', 'armor': 'armor',
        'operations': 'operations', 'capital_ships': 'capital_ships',
        'carriers': 'carriers', 'screens': 'screens', 'submarines': 'submarines',
        'fighter_aircraft': 'fighters', 'strike_aircraft': 'strikers',
        'medium_aircraft': 'mediums', 'heavy_aircraft': 'heavies',
    }
    effects = ['# Generated by tools/generate_doctrine_switch.py.\n']
    decisions = ['# Generated by tools/generate_doctrine_switch.py.\n',
                 'tfr_doctrine_reorganization = {']
    ui = []
    loc = ['l_english:',
           ' tfr_doctrine_reorganization: "Doctrine Reorganization"',
           ' tfr_doctrine_reorganization_desc: "Change your land, naval or air Grand Doctrine while retaining selected Subdoctrines and their current Mastery. You can also use Change Grand Doctrine Keep Subdoctrines below the main Grand Doctrine button. Reserved Mastery is not retained."',
           ' tfr_keep_doctrine_mastery_tt: "Retain selected Subdoctrines, all unlocked rewards and current Mastery in this branch. Completed tracks activate the new Grand Doctrine milestones. Reserved Mastery is not retained."',
           ' tfr_doctrine_cost_army: "£army_experience §Y100§!"',
           ' tfr_doctrine_cost_navy: "£navy_experience §Y100§!"',
           ' tfr_doctrine_cost_air: "£air_experience §Y100§!"',
           ' tfr_doctrine_ui_open: "Change Grand Doctrine Keep Subdoctrines"',
           ' tfr_doctrine_ui_title: "Change Grand Doctrine — keep Mastery"',
           ' tfr_doctrine_ui_help: "Selected Subdoctrines and current Mastery are retained; Reserved Mastery is not retained. Cost: 100 XP. After switching, click the doctrine tab to refresh its title."',
           ' tfr_doctrine_ui_open_tt: "Change land, naval or air Grand Doctrine while keeping Subdoctrine Mastery."',
           ' tfr_doctrine_ui_switch_tt: "Click to switch immediately for 100 XP from this service, retaining selected Subdoctrines and current Mastery. Reserved Mastery is not retained. Requires an existing Grand Doctrine and at least 100 XP; the current doctrine cannot be selected again."',
           ' tfr_doctrine_ui_land: "Land — £army_experience 100"',
           ' tfr_doctrine_ui_naval: "Naval — £navy_experience 100"',
           ' tfr_doctrine_ui_air: "Air — £air_experience 100"']

    for filename in ['land_grand_doctrines.txt', 'sea_grand_doctrines.txt',
                     'air_grand_doctrines.txt']:
        grands = read(ROOT / 'common/doctrines/grand_doctrines' / filename)
        folder = get(grands[0][1], 'folder')
        tracks = [v for k, v in get(grands[0][1], 'tracks')]
        for _, fields in grands:
            assert [v for k, v in get(fields, 'tracks')] == tracks
            assert get(fields, 'xp_cost') == '100'
            assert get(fields, 'available') == [('always', 'yes')]

        for track in tracks:
            effects.append(track_effects(track, folder))

        effects.append(f'tfr_save_{folder}_doctrines = {{')
        for track in tracks:
            effects.append(f'    set_variable = {{ tfr_saved_sub_{track} = 0 }}')
            for index, name in enumerate(definitions[track], 1):
                keyword = 'if' if index == 1 else 'else_if'
                effects.extend([f'    {keyword} = {{',
                                f'        limit = {{ has_doctrine = {name} }}',
                                f'        set_variable = {{ tfr_saved_sub_{track} = {index} }}',
                                '    }'])
            effects.append(f'    tfr_save_{track}_mastery = yes')
            counter = counter_names[track] + '_milestone_var'
            effects.extend([
                f'    set_variable = {{ tfr_saved_counter_exists_{track} = 0 }}',
                f'    if = {{ limit = {{ has_variable = {counter} }}',
                f'        set_variable = {{ tfr_saved_counter_exists_{track} = 1 }}',
                f'        set_variable = {{ tfr_saved_counter_{track} = {counter} }}',
                '    }'])
        effects.append('}\n')
        effects.append(f'tfr_restore_{folder}_doctrines = {{')
        for slot, track in enumerate(tracks):
            for index, name in enumerate(definitions[track], 1):
                keyword = 'if' if index == 1 else 'else_if'
                effects.extend([f'    {keyword} = {{',
                    f'        limit = {{ check_variable = {{ tfr_saved_sub_{track} = {index} }} }}',
                    f'        set_sub_doctrine = {{ sub_doctrine = {name} folder = {folder} track = {slot} }}',
                    '    }'])
            effects.extend([
                f'    tfr_restore_{track}_mastery = yes',
                f'    clear_variable = tfr_saved_sub_{track}'])
            counter = counter_names[track] + '_milestone_var'
            effects.extend([
                f'    if = {{ limit = {{ check_variable = {{ tfr_saved_counter_exists_{track} = 1 }} }}',
                f'        set_variable = {{ {counter} = tfr_saved_counter_{track} }}',
                '    }', f'    else = {{ clear_variable = {counter} }}',
                f'    clear_variable = tfr_saved_counter_{track}',
                f'    clear_variable = tfr_saved_counter_exists_{track}'])
        effects.extend(['    tfr_clear_doctrine_snapshot = yes', '}\n'])

        for name, fields in grands:
            xp = get(fields, 'xp_type')
            ui.append((name, folder, xp, get(fields, 'name')))
            decision = 'tfr_switch_' + name
            decisions.extend([
                f'    {decision} = {{', '        icon = generic_military',
                '        allowed = { always = yes }',
                f'        visible = {{ is_ai = no has_any_grand_doctrine = {folder} NOT = {{ has_doctrine = {name} }} }}',
                f'        available = {{ has_{xp}_experience > 99.99999 NOT = {{ has_doctrine = {name} }} }}',
                f'        custom_cost_trigger = {{ has_{xp}_experience > 99.99999 }}',
                f'        custom_cost_text = tfr_doctrine_cost_{xp}',
                '        cost = 0', '        fire_only_once = no',
                '        ai_will_do = { factor = 0 }',
                '        complete_effect = {',
                '            custom_effect_tooltip = tfr_keep_doctrine_mastery_tt',
                '            hidden_effect = {',
                f'                tfr_save_{folder}_doctrines = yes',
                f'                set_grand_doctrine = {name}',
                f'                tfr_restore_{folder}_doctrines = yes',
                f'                {xp}_experience = -100',
                '            }', '        }', '    }'])
            loc.extend([
                f' {decision}: "Switch to ${get(fields, "name")}$ (keep Mastery)"',
                f' {decision}_desc: "Adopt ${get(fields, "name")}$ for 100 {xp.title()} XP while retaining selected Subdoctrines and their current Mastery. Reserved Mastery is not retained."'])
    decisions.append('}')
    generate_gui(ui)
    (ROOT / 'common/scripted_effects/TFR_doctrine_switch_generated.txt').write_text(
        '\n'.join(effects) + '\n', encoding='utf-8', newline='\n')
    (ROOT / 'common/decisions/TFR_doctrine_switch.txt').write_text(
        '\n'.join(decisions) + '\n', encoding='utf-8', newline='\n')
    (ROOT / 'localisation/english/TFR_doctrine_switch_l_english.yml').write_text(
        '\n'.join(loc) + '\n', encoding='utf-8-sig', newline='\n')
    replace_dir = ROOT / 'localisation/english/replace'
    replace_dir.mkdir(exist_ok=True)
    (replace_dir / 'TFR_doctrine_switch_ui_l_english.yml').write_text(
        'l_english:\n'
        ' SWITCH_GRAND_DOCTRINE_MASTERY_RESET: "§RAll§! £doctrine_mastery §HMastery§!§R is reset when switching Grand Doctrine here.§!\\nTo keep Subdoctrine Mastery, use §YChange Grand Doctrine Keep Subdoctrines§! below the main Grand Doctrine button. Reserved Mastery is not retained."\n',
        encoding='utf-8-sig', newline='\n')
    print(f'Generated {len(parse(chr(10).join(decisions))[0][1])} doctrine choices; land, naval and air.')



def generate_gui(choices):
    """Attach to the native doctrine view without copying the vanilla layout."""
    gui = (ROOT / 'tools/doctrine_switch_gui.template.gui').read_text(encoding='utf-8')
    buttons, effects, triggers = [], [], []
    for column, folder in enumerate(['land', 'naval', 'air']):
        for row, (name, _, xp, label) in enumerate(c for c in choices if c[1] == folder):
            button = 'switch_' + name
            requirement = (f'has_any_grand_doctrine = {folder} '
                           f'has_{xp}_experience > 99.99999 '
                           f'NOT = {{ has_doctrine = {name} }}')
            buttons.append(f'''        buttonType = {{
            name = "{button}"
            position = {{ x = {24 + column * 290} y = {134 + row * 64} }}
            size = {{ x = 274 y = 56 }}
            spriteType = "GFX_tiled_decisions_bg_small"
            buttonText = "{label}"
            buttonFont = "hoi_18mbs"
            pdx_tooltip = "tfr_doctrine_ui_switch_tt"
            clicksound = click_ok
        }}''')
            # Snapshot meta-effects must not run while building button tooltips.
            effects.append(f'''            {button}_click = {{
                hidden_effect = {{
                    if = {{
                        limit = {{ {requirement} }}
                        tfr_save_{folder}_doctrines = yes
                        set_grand_doctrine = {name}
                        tfr_restore_{folder}_doctrines = yes
                        {xp}_experience = -100
                        clr_country_flag = tfr_doctrine_selector_open
                    }}
                }}
            }}''')
            triggers.append(f'            {button}_click_enabled = {{ {requirement} }}')
    (ROOT / 'interface/TFR_doctrine_switch.gui').write_text(
        gui.replace('$BUTTONS$', '\n'.join(buttons)), encoding='utf-8', newline='\n')
    scripted = '''# Generated by tools/generate_doctrine_switch.py.
scripted_gui = {
    tfr_doctrine_selector_open = {
        context_type = player_context
        ai_enabled = { always = no }
        window_name = "tfr_doctrine_selector_open_window"
        parent_window_name = "country_doctrine_view"
        effects = {
            open_click = {
                if = { limit = { has_country_flag = tfr_doctrine_selector_open } clr_country_flag = tfr_doctrine_selector_open }
                else = { set_country_flag = tfr_doctrine_selector_open }
            }
        }
    }
    tfr_doctrine_selector = {
        context_type = player_context
        ai_enabled = { always = no }
        window_name = "tfr_doctrine_selector_window"
        parent_window_name = "country_doctrine_view"
        visible = { has_country_flag = tfr_doctrine_selector_open }
        effects = {
            close_click = { clr_country_flag = tfr_doctrine_selector_open }
$EFFECTS$
        }
        triggers = {
$TRIGGERS$
        }
    }
}
'''
    (ROOT / 'common/scripted_guis/TFR_doctrine_switch.txt').write_text(
        scripted.replace('$EFFECTS$', '\n'.join(effects)).replace('$TRIGGERS$', '\n'.join(triggers)),
        encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
